let current = localStorage.getItem('ath_lang') || (navigator.language || 'de').slice(0, 2);
if (!STRINGS[current]) current = 'de';

export function getLang() { return current; }

export function setLang(code) {
  if (!STRINGS[code]) return;
  current = code;
  localStorage.setItem('ath_lang', code);
  document.documentElement.lang = code;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

export function timeAgo(iso) {
  const diff = Date.now() - new Date(iso).getTime();
  const min = Math.floor(diff / 60000);
  if (min < 1) return t('time.now');
  if (min < 60) return t('time.min', { n: min });
  const h = Math.floor(min / 60);
  if (h < 24) return t('time.hour', { n: h });
  return t('time.day', { n: Math.floor(h / 24) });
}

